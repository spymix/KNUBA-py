n = int(input("Введіть число n: "))

if 1 <= n <= 9:
    print("Число однозначне")
elif 10 <= n <= 99:
    print("Число двозначне")
elif 100 <= n <= 999:
    print("Число тризначне")
else:
    print("Число не є одно-, дво- або тризначним")

if n % 2 == 0:
    print("Число парне")
else:
    print("Число непарне")

if n % 10 == 6:
    print("Остання цифра числа — 6")
